"""Derive the duplex training mix from the SALM v4 input_cfg.

Keeps the French single-audio-turn sources, switches them to `type: conversation_as_duplex`, and
rebalances them into buckets with fixed shares (inside a bucket, the v4 relative weights are kept).

    python make_input_cfg.py  # writes conf/data/input_cfg_duplex_fr.yaml
"""

import re
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "training/conf/data/v4/input_cfg_train_weighted_randomorder_sharded.yaml"
DST = HERE / "conf/data/input_cfg_duplex_fr.yaml"

# bucket -> (share, manifest path regex). A path goes to the first bucket that matches.
BUCKETS = {
    # "question -> answer": the core conversational turn-taking signal.
    "spoken_qa_fr": (0.35, r"/question-answering/qa_audio-question-only/fr/"),
    # Audio context + text question (the question becomes the system prompt).
    "context_qa_fr": (0.10, r"/question-answering/qa_audio-context-text-question/fr/"),
    # Instruction ("transcris...") as system prompt, transcript as the agent turn.
    "asr_fr": (0.45, r"/asr/fr/context/"),
    "ast_from_fr": (0.10, r"/ast/fr-[a-z]+/context/"),
}
# Per-bucket extra keys for conversation_as_duplex (see duplex_data.py).
EXTRA = {
    "spoken_qa_fr": {"max_agent_tokens": 400},
    "context_qa_fr": {"max_agent_tokens": 400},
}


def leaves(node, weight=1.0):
    """Yield (absolute weight, leaf dict) for every manifest entry of a nested input_cfg."""
    if isinstance(node, list):
        for item in node:
            yield from leaves(item, weight)
    elif "input_cfg" in node:
        yield from leaves(node["input_cfg"], weight * node.get("weight", 1.0))
    else:
        yield weight * node.get("weight", 1.0), node


def main():
    src = yaml.safe_load(SRC.read_text())
    picked = {b: [] for b in BUCKETS}
    for w, leaf in leaves(src):
        if leaf.get("type") != "multimodal_conversation":
            continue
        for bucket, (_, pattern) in BUCKETS.items():
            if re.search(pattern, leaf["manifest_filepath"]):
                picked[bucket].append((w, leaf))
                break

    # Top-level list of groups, like the v4 input_cfg: every top-level item needs a `type`.
    groups = []
    for bucket, (share, _) in BUCKETS.items():
        entries = picked[bucket]
        assert entries, f"no v4 manifest matched bucket {bucket}"
        total = sum(w for w, _ in entries)
        items = []
        for w, leaf in entries:
            item = {k: v for k, v in leaf.items() if k not in ("type", "weight")}
            item["type"] = "conversation_as_duplex"
            item["weight"] = round(w / total, 4)
            item.update(EXTRA.get(bucket, {}))
            items.append(item)
        groups.append({"type": "group", "weight": share, "tags": {"bucket": bucket}, "input_cfg": items})
        print(f"{bucket:<14} share={share:.2f}  {len(items):2d} manifests")

    header = (
        f"# GENERATED by train_duplex/make_input_cfg.py from {SRC.relative_to(HERE.parent)}. Do not edit by hand.\n"
        "# French single-audio-turn SALM sources reused as 'listen, then answer' duplex examples.\n"
        "# Real two-channel dialogues (barge-in, backchannels) will go here as extra groups, e.g.:\n"
        "#   - type: lhotse_shar\n"
        "#     shar_path: <dir with cuts.*.jsonl.gz + recording.*.tar>  # supervisions speaker=user/agent\n"
        "#     weight: 0.3\n"
    )
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(header + yaml.safe_dump(groups, sort_keys=False, allow_unicode=True, width=200))
    print(f"-> {DST}")


if __name__ == "__main__":
    main()
